/** ตอบจากกฎในตัว: ตรวจความเสี่ยง → ตรวจหัวข้อจากข้อความล่าสุด → เลือกคำตอบตามลำดับการคุย */
export function localReply(messages, hint = "chat") {
  const users = (messages || []).filter((m) => m.role === "user");
  const last = users[users.length - 1]?.content || "";

  const risk = assessRisk(last);
  if (risk === "crisis") return crisisReply();
  if (risk === "safety") return safetyReply();

  const t = normalize(last);
  let key = detectTopic(last);
  if (!key) {
    if (THANKS.test(t)) key = "thanks";
    else if (BYE.test(t)) key = "bye";
    else if (GREET.test(t)) key = "greeting";
    else {
      // ข้อความสั้น ๆ ที่ไม่มีคำบอกหัวข้อ → คุยต่อเรื่องเดิมที่ค้างอยู่
      const prevKey = users
        .slice(0, -1)
        .reverse()
        .map((m) => detectTopic(m.content))
        .find((k) => k && REPLIES[k] && !["safe", "joke", "nobody"].includes(k));
      if (prevKey) key = prevKey;
      else if (hint && hint !== "chat" && REPLIES[hint] && users.length <= 1) key = hint;
      else key = "unknown";
    }
  }

  const list = REPLIES[key] || REPLIES.unknown;
  const prior = users.slice(0, -1);
  const stage =
    key === "unknown"
      ? prior.length
      : prior.filter((m) => detectTopic(m.content) === key).length;
  const pick = list[stage % list.length];
  return { risk: "none", reply: pick.reply, suggestions: pick.suggestions, fallback: true };
}

// เวอร์ชันเดิม (รับแค่หัวข้อ)
export function fallbackReply(topic) {
  const list = REPLIES[topic] || REPLIES.greeting;
  return { risk: "none", reply: list[0].reply, suggestions: list[0].suggestions, fallback: true };
}