/** @returns {"crisis" | "safety" | "none"} */
export function assessRisk(text) {
  const t = normalize(text);
  if (!t) return "none";
  if (CRISIS.some((k) => t.includes(k))) return "crisis";
  if (SAFETY.some((k) => t.includes(k))) return "safety";
  return "none";
}

export function assessHistory(messages) {
  let worst = "none";
  for (const m of messages) {
    if (m.role !== "user") continue;
    const r = assessRisk(m.content);
    if (r === "crisis") return "crisis";
    if (r === "safety") worst = "safety";
  }
  return worst;
}

