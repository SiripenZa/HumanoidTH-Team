export function detectTopic(text) {
  const t = normalize(text);
  if (!t) return null;
  let best = null;
  let bestScore = 0;
  for (const [key, words] of Object.entries(TOPIC_KEYWORDS)) {
    let score = 0;
    for (const w of words) if (t.includes(w)) score += w.length;
    if (score > bestScore) {
      best = key;
      bestScore = score;
    }
  }
  return best;
}

