export type AssessmentLevel = "low" | "moderate" | "high";

export type AssessmentSummary = {
  level?: AssessmentLevel;
  score?: number;
  maxScore?: number;
  concerns: Topic[];
};

export const ASSESSMENT_LEVELS: AssessmentLevel[] = ["low", "moderate", "high"];
export const ASSESSMENT_TOPICS: Topic[] = ["stress", "bored", "study", "friends", "family", "sleep", "sad", "vent"];

function levelFromText(s: string): AssessmentLevel | undefined {
  const t = s.toLowerCase();
  if (/moderate|medium|ปานกลาง/.test(t)) return "moderate";
  if (/high|severe|สูง|รุนแรง/.test(t)) return "high";
  if (/low|mild|minimal|ต่ำ|น้อย|ปกติ/.test(t)) return "low";
  return undefined;
}

function firstOf(obj: Record<string, unknown>, keys: string[]): unknown {
  for (const k of keys) if (obj[k] !== undefined && obj[k] !== null) return obj[k];
  return undefined;
}

function toNumber(v: unknown): number | undefined {
  const n = typeof v === "string" ? Number(v) : v;
  return typeof n === "number" && Number.isFinite(n) ? n : undefined;
}

// Tolerant reader: the check-in page may store the result under different field names,
// so we look for the common ones. Returns null when nothing usable is found.
export function parseAssessment(raw: unknown): AssessmentSummary | null {
  let data: unknown = raw;
  if (typeof raw === "string") {
    try {
      data = JSON.parse(raw);
    } catch {
      const level = levelFromText(raw);
      return level ? { level, concerns: [] } : null;
    }
  }
  if (!data || typeof data !== "object" || Array.isArray(data)) return null;
  const obj = data as Record<string, unknown>;

  let level: AssessmentLevel | undefined;
  const levelRaw = firstOf(obj, ["level", "stressLevel", "stress_level", "riskLevel", "severity", "category", "result", "status", "label"]);
  if (typeof levelRaw === "string") level = levelFromText(levelRaw);

  const score = toNumber(firstOf(obj, ["score", "totalScore", "stressScore", "total", "points"]));
  const maxScore = toNumber(firstOf(obj, ["maxScore", "max", "maxPoints", "totalPossible"]));
  if (!level && score !== undefined && maxScore && maxScore > 0) {
    const ratio = score / maxScore;
    level = ratio < 0.34 ? "low" : ratio < 0.67 ? "moderate" : "high";
  }

  const list = firstOf(obj, ["concerns", "topics", "stressors", "sources", "areas", "categories", "tags"]);
  const items: string[] = Array.isArray(list)
    ? list.filter((x): x is string => typeof x === "string")
    : typeof list === "string"
      ? list.split(/[,;]/)
      : [];
  const concerns: Topic[] = [];
  for (const item of items) {
    // Accept a topic id directly ("study"), Thai text, or English text.
    const trimmed = item.trim().toLowerCase();
    const direct = (ASSESSMENT_TOPICS as string[]).includes(trimmed) ? (trimmed as Topic) : undefined;
    const tp = direct ?? detectTopic(item) ?? detectTopicEn(item);
    if (tp && !concerns.includes(tp)) concerns.push(tp);
  }

  return { level, score, maxScore, concerns: concerns.slice(0, 3) };
}

